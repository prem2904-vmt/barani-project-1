/** Every built-in picture, in the order the template picker shows them. */
export const TEMPLATES: readonly CanvasTemplate[] = [
  T_BODY_FRONT,
  T_BODY_BACK,
  T_HAND,
  T_FOOT,
  T_FACE,
  T_EAR,
  T_EYE_ANTERIOR,
  T_FUNDUS,
  T_ABDOMEN,
  T_TEETH,
];

/** A built-in picture by id; null for an unknown, empty or missing id. */
export function templateById(id: string | null | undefined): CanvasTemplate | null {
  if (!id) return null;
  return TEMPLATES.find((t) => t.id === id) ?? null;
}

/** The API's starter ids → the mock artwork that stands in for them. */
export const MOCK_STARTERS: Record<string, string> = {
  'body-front': 'body-front',
  'body-back': 'body-back',
  'head-face': 'face',
  'eye-front': 'eye-anterior',
  'tooth-chart': 'teeth',
  'abdomen-quadrants': 'abdomen',
};

const f4 = (n: number) => Math.round(n * 10000) / 10000;

/** A mock starter picture in the API's shape (areas as polygons in fractions; ovals become 24-point polygons). */
export function mockStarter(apiId: string, svgBase = ''): StarterPicture | null {
  const t = templateById(MOCK_STARTERS[apiId] ?? '');
  if (!t) return null;
  return {
    id: apiId,
    title: t.name,
    width: t.w,
    height: t.h,
    svgUrl: `${svgBase}/api/canvas/templates/${apiId}.svg`,
    regions: t.regions.map((r) => {
      const s = r.shape;
      const pts: [number, number][] = [];
      if (s.type === 'ellipse')
        for (let i = 0; i < 24; i++) {
          const a = (i / 24) * Math.PI * 2;
          pts.push([f4((s.cx + s.rx * Math.cos(a)) / t.w), f4((s.cy + s.ry * Math.sin(a)) / t.h)]);
        }
      else for (let i = 0; i + 1 < s.points.length; i += 2) pts.push([f4(s.points[i] / t.w), f4(s.points[i + 1] / t.h)]);
      return { id: r.key.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase()), label: r.label, points: pts };
    }),
  };
}

export function mockStarters(svgBase = ''): StarterInfo[] {
  return Object.keys(MOCK_STARTERS).map((id) => {
    const { regions: _r, ...info } = mockStarter(id, svgBase)!;
    return info;
  });
}

/** The mock starter as a standalone SVG (light fill, slate lines, like the API's). */
export function mockStarterSvg(apiId: string): string | null {
  const t = templateById(MOCK_STARTERS[apiId] ?? '');
  if (!t) return null;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${t.w} ${t.h}" width="${t.w}" height="${t.h}"><g color="#334155">${t.art}</g></svg>`;
}
